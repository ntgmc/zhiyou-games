import { seededRandom, STANDARD_CODES } from "./engine.js";
import type { Counts, Lesson, Mission, Noise, Packet } from "./types.js";

function tokens(counts: Counts, seed: string) {
  const bag = Object.entries(counts).flatMap(([id, n]) => Array(n).fill(id));
  const random = seededRandom(seed);
  for (let i = bag.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [bag[i], bag[j]] = [bag[j], bag[i]];
  }
  return bag;
}

function packet(id: string, name: string, counts: Counts, deadline = 1, extra: Partial<Packet> = {}): Packet {
  return { id, name, tokens: tokens(counts, id), deadline, required: true, priority: "常规", description: "导航指令", ...extra };
}

function scheduledPackets(mission: number, rows: [string, string, Counts, number, number][]): Packet[] {
  return rows.map(([id, name, counts, releaseRound, deadline]) => packet(`shift-${mission}-${id}`, name, counts, deadline, {
    releaseRound, description: `第 ${releaseRound} 轮抵达，第 ${deadline} 轮截止。独立成包。`,
  }));
}

